/// Standard icon sizing tokens to ensure icons are consistently scaled.
class AppIconSize {
  AppIconSize._();

  /// Small size, typical for trailing icons inside inputs or small context actions.
  static const double s = 18.0;

  /// Medium size, standard for navigation items, app bar actions, and normal buttons.
  static const double m = 24.0;

  /// Large size, used in headers or feature highlights.
  static const double l = 32.0;
}
