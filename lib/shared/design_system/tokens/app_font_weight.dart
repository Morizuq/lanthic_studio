import 'package:flutter/material.dart';

/// Centralized font weight design tokens.
class AppFontWeight {
  AppFontWeight._();

  /// Regular weight (w400) - default for body text.
  static const FontWeight regular = FontWeight.w400;

  /// Medium weight (w500) - standard for button labels and navigation items.
  static const FontWeight medium = FontWeight.w500;

  /// Semi-bold weight (w600) - used for card headers and section titles.
  static const FontWeight semiBold = FontWeight.w600;

  /// Bold weight (w700) - used for prominent headings.
  static const FontWeight bold = FontWeight.w700;
}
